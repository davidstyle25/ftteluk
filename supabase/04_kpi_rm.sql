-- Jalankan di Supabase Studio > SQL Editor (aman dijalankan ulang).
-- Semua user login boleh MELIHAT; hanya admin yang boleh tambah/ubah/hapus.
-- ============================================================================

create table if not exists public.kpi_rm_views (
  id         bigint generated by default as identity primary key,
  nama       text  not null,                          -- nama RM
  periode    text  not null default 'MYCORE',         -- judul periode, mis. "MYCORE Juni 2026"
  rows       jsonb not null default '[]'::jsonb,      -- isi baris tabel (bisa diedit)
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.kpi_rm_views enable row level security;

drop policy if exists kpi_rm_views_select on public.kpi_rm_views;
drop policy if exists kpi_rm_views_insert on public.kpi_rm_views;
drop policy if exists kpi_rm_views_update on public.kpi_rm_views;
drop policy if exists kpi_rm_views_delete on public.kpi_rm_views;

create policy kpi_rm_views_select on public.kpi_rm_views
  for select to authenticated using (true);

create policy kpi_rm_views_insert on public.kpi_rm_views
  for insert to authenticated
  with check ((select public.has_role((select auth.uid()), 'admin')));

create policy kpi_rm_views_update on public.kpi_rm_views
  for update to authenticated
  using      ((select public.has_role((select auth.uid()), 'admin')))
  with check ((select public.has_role((select auth.uid()), 'admin')));

create policy kpi_rm_views_delete on public.kpi_rm_views
  for delete to authenticated
  using ((select public.has_role((select auth.uid()), 'admin')));

revoke all on public.kpi_rm_views from anon;
grant select, insert, update, delete on public.kpi_rm_views to authenticated;

notify pgrst, 'reload schema';

